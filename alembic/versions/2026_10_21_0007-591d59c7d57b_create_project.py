def first_project_name(owner_name: str | None, taken: set[str]) -> str:
    """ "My first project", with the owner's name when given, numbered if that's
    already taken (two people can share a name)."""
    base = FIRST_PROJECT_NAME
    if owner_name and owner_name.strip():
        base = f"{FIRST_PROJECT_NAME} ({owner_name.strip()})"
    number = 1
    while True:
        suffix = "" if number == 1 else f" {number}"
        name = shorten(base, NAME_MAX_LENGTH - len(suffix)) + suffix
        if name.lower() not in taken:
            return name
        number += 1


