import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import Engine, inspect, text
from sqlalchemy.dialects.postgresql.base import PGInspector

from anvil import PROJECT_ROOT

BEFORE_PROJECTS = "42aa21518a59"


def alembic(engine: Engine, cmd, *args: str) -> None:
    """Run an Alembic command against `engine` instead of DATABASE_URL."""
    # No ini file: alembic.ini only configures logging, which would
    # otherwise reset pytest's log capture.
    config = Config(toml_file=PROJECT_ROOT / "pyproject.toml")
    with engine.begin() as connection:
        config.attributes["connection"] = connection
        cmd(config, *args)


def test_migrations_match_models(empty_db: Engine) -> None:
    alembic(empty_db, command.upgrade, "head")

    try:
        alembic(empty_db, command.check)
    except AutogenerateDiffsDetected as diffs:
        pytest.fail(
            f"Models and migrations differ; run `alembic revision --autogenerate`.\n{diffs}"
        )


def test_upgrade_downgrade_round_trip(empty_db: Engine) -> None:
    alembic(empty_db, command.upgrade, "head")
    alembic(empty_db, command.downgrade, "base")

    inspector = inspect(empty_db)
    assert isinstance(inspector, PGInspector)
    assert inspector.get_table_names() == ["alembic_version"]
    # Postgres keeps enum types after their table is dropped.
    assert inspector.get_enums() == []

    alembic(empty_db, command.upgrade, "head")


def add_person_with_requirements(engine: Engine, name: str, count: int = 1) -> None:
    """Insert a Point of Contact and `count` Requirements, as before Projects."""
    with engine.begin() as connection:
        person_id = connection.execute(
            text(
                "INSERT INTO point_of_contact (id, name, email)"
                " VALUES (gen_random_uuid(), :name, gen_random_uuid() || '@example.com')"
                " RETURNING id"
            ),
            {"name": name},
        ).scalar_one()
        for _ in range(count):
            connection.execute(
                text(
                    "INSERT INTO requirement (id, point_of_contact_id, idea, title)"
                    " VALUES (gen_random_uuid(), :person, 'An idea', 'Idea')"
                ),
                {"person": person_id},
            )


def first_projects(engine: Engine) -> list[tuple[str, str, int]]:
    """Each Project's name, owner's name and number of Requirements, by name."""
    with engine.connect() as connection:
        rows = connection.execute(
            text(
                """
                SELECT project.name, point_of_contact.name, count(requirement.id)
                FROM project
                JOIN point_of_contact ON point_of_contact.id = project.owner_id
                LEFT JOIN requirement
                    ON requirement.project_id = project.id
                    AND requirement.point_of_contact_id = project.owner_id
                GROUP BY project.id, point_of_contact.name
                ORDER BY project.name
                """
            )
        )
        return [tuple(row) for row in rows]


def test_upgrade_puts_a_lone_owners_requirements_in_my_first_project(
    empty_db: Engine,
) -> None:
    alembic(empty_db, command.upgrade, BEFORE_PROJECTS)
    add_person_with_requirements(empty_db, "Ada", count=2)

    alembic(empty_db, command.upgrade, "head")

    assert first_projects(empty_db) == [("My first project", "Ada", 2)]
    with empty_db.connect() as connection:
        context = connection.execute(text("SELECT context FROM project")).scalar_one()
    assert context == ""


def test_upgrade_adds_owner_names_when_first_projects_would_clash(
    empty_db: Engine,
) -> None:
    alembic(empty_db, command.upgrade, BEFORE_PROJECTS)
    add_person_with_requirements(empty_db, "Ada")
    add_person_with_requirements(empty_db, "Grace")
    add_person_with_requirements(empty_db, "Grace")
    with empty_db.begin() as connection:
        connection.execute(
            text(
                "INSERT INTO point_of_contact (id, name, email)"
                " VALUES (gen_random_uuid(), 'No requirements', 'none@example.com')"
            )
        )

    alembic(empty_db, command.upgrade, "head")

    assert first_projects(empty_db) == [
        ("My first project (Ada)", "Ada", 1),
        ("My first project (Grace)", "Grace", 1),
        ("My first project (Grace) 2", "Grace", 1),
    ]


def test_downgrade_drops_projects_and_keeps_requirements(empty_db: Engine) -> None:
    alembic(empty_db, command.upgrade, BEFORE_PROJECTS)
    add_person_with_requirements(empty_db, "Ada")
    alembic(empty_db, command.upgrade, "head")

    alembic(empty_db, command.downgrade, BEFORE_PROJECTS)

    inspector = inspect(empty_db)
    assert "project" not in inspector.get_table_names()
    columns = [column["name"] for column in inspector.get_columns("requirement")]
    assert "project_id" not in columns
    with empty_db.connect() as connection:
        assert (
            connection.execute(text("SELECT count(*) FROM requirement")).scalar() == 1
        )
