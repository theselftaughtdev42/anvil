import { expect, test } from 'vitest'
import { featureFilename, type GherkinToken, tokenizeGherkin } from '@/lib/gherkin'

const line = (text: string) => tokenizeGherkin(text)[0]
const kinds = (tokens: GherkinToken[]) => tokens.map(({ text, kind }) => [text, kind ?? null])

test.each([
  ['Feature: Rebook a missed delivery', 'Feature:', 'Rebook a missed delivery', ''],
  ['  Background:', 'Background:', '', '  '],
  ['  Rule: Only working days', 'Rule:', 'Only working days', '  '],
  ['    Scenario: Another day', 'Scenario:', 'Another day', '    '],
  ['    Scenario Outline: Every status', 'Scenario Outline:', 'Every status', '    '],
  ['      Examples:', 'Examples:', '', '      '],
])('%j is a keyword and a title', (text, keyword, title, indent) => {
  expect(kinds(line(text))).toEqual(
    [
      [indent, null],
      [keyword, 'keyword'],
      [title && ' ', null],
      [title, 'title'],
    ].filter(([text]) => text),
  )
})

test.each(['Given', 'When', 'Then', 'And', 'But'])('%s is a step keyword', (keyword) => {
  expect(kinds(line(`    ${keyword} it moves`))).toEqual([
    ['    ', null],
    [keyword, 'step'],
    [' it moves', null],
  ])
})

test('a step picks out strings and placeholders, inside strings too', () => {
  expect(kinds(line('    Given "<title>" is <status> in "Parcels"'))).toEqual([
    ['    ', null],
    ['Given', 'step'],
    [' ', null],
    ['"', 'string'],
    ['<title>', 'placeholder'],
    ['"', 'string'],
    [' is ', null],
    ['<status>', 'placeholder'],
    [' in ', null],
    ['"Parcels"', 'string'],
  ])
})

test('a placeholder can have spaces in it, as an Examples column can', () => {
  expect(kinds(line('    Given <due date> is set'))).toEqual([
    ['    ', null],
    ['Given', 'step'],
    [' ', null],
    ['<due date>', 'placeholder'],
    [' is set', null],
  ])
})

test('a step keyword only counts as a whole word at the start', () => {
  expect(kinds(line('  Andrew rebooks it'))).toEqual([['  Andrew rebooks it', 'description']])
})

test('a table row splits into pipes and cells, keeping escaped pipes in their cell', () => {
  expect(kinds(line('        | a \\| b | <x> |'))).toEqual([
    ['        ', null],
    ['|', 'pipe'],
    [' ', null],
    ['a \\| b', 'cell'],
    [' ', null],
    ['|', 'pipe'],
    [' ', null],
    ['<x>', 'placeholder'],
    [' ', null],
    ['|', 'pipe'],
  ])
})

test('an escaped backslash before a pipe ends the cell', () => {
  expect(kinds(line('| a\\\\ | b |')).filter(([, kind]) => kind === 'cell')).toEqual([
    ['a\\\\', 'cell'],
    ['b', 'cell'],
  ])
})

test('a comment is one token', () => {
  expect(kinds(line('  # Generated by Anvil'))).toEqual([['  # Generated by Anvil', 'comment']])
})

test.each(['As a', 'As an', 'I want', 'So that', 'Out of scope:'])('a description opening with %j', (opening) => {
  expect(kinds(line(`  ${opening} rest`))).toEqual([
    ['  ', null],
    [opening, 'narrative'],
    [' rest', 'description'],
  ])
})

test.each(['As another option', 'I wanted more', 'So thatched'])('%j only opens a description by whole words', (text) => {
  expect(kinds(line(`  ${text}`))).toEqual([[`  ${text}`, 'description']])
})

test('other description lines and blank lines', () => {
  expect(kinds(line('    - Moving Requirements'))).toEqual([['    - Moving Requirements', 'description']])
  expect(tokenizeGherkin('Feature: A\n\n  Scenario: B\n')[1]).toEqual([])
})

test('the tokens join back into the content, one line per line', () => {
  const content = [
    'Feature: Rebook a missed delivery',
    '  As a customer',
    '',
    '  Scenario Outline: Rebook "<day>"',
    '    Given a parcel | with a pipe',
    '',
    '      Examples:',
    '        | day      |',
    '        | Mon \\| Tue |',
    '',
  ].join('\n')
  const lines = tokenizeGherkin(content)
  expect(lines.map((tokens) => tokens.map(({ text }) => text).join('')).join('\n') + '\n').toBe(content)
  expect(tokenizeGherkin('Feature: A')).toHaveLength(1)
})

test.each([
  ['Rebook a missed delivery', 'rebook-a-missed-delivery.feature'],
  ['  Delete a Project — and its Requirements!  ', 'delete-a-project-and-its-requirements.feature'],
  ['Café crème', 'cafe-creme.feature'],
  ['Export VAT/GST report (2026)', 'export-vat-gst-report-2026.feature'],
  ['日本語のタイトル', '日本語のタイトル.feature'],
  ['???', 'requirement.feature'],
  ['a'.repeat(79) + ' b', `${'a'.repeat(79)}.feature`],
])('%j downloads as %j', (title, filename) => {
  expect(featureFilename(title)).toBe(filename)
})
